"""ml/dyno_classifier.py -- fault classifier for a MEASURED surface
dynamometer card, trained on SYNTHETIC cards generated by the physics twin
(twin.dyno.compute_cards()), not on any real field data.

Why synthetic training data. PS SIH26120 asks the twin to ingest a measured
surface card (position vs. load) from the field and return a fault read --
full pump / fluid pound / gas interference / heavy-oil viscous drag / rod
float (carrier-bar separation). Oil India has not handed over a real card, so
this module sweeps twin.dyno.compute_cards() (docs/model-improvement/
DYNO_CARD_MODEL.md has the fault signatures and the JSON shape) over spm, oil
viscosity, pump fillage, water cut, the gas-interference option and small
rod-string geometry perturbations, adds measurement noise and irregular
resampling to imitate a real card reader, and trains a RandomForestClassifier
on shape features of the SURFACE card alone (position_m, load_surface_kN --
what a beam-inclinometer dynamometer actually records; the downhole/pump card
computed alongside it is only used to derive the ground-truth label via
compute_cards()'s own card_type, exactly as a specialist would read a
downhole card off a measured surface one).

*** DOMAIN-SHIFT CAVEAT ***
This classifier has NEVER seen a real dynamometer card. It is trained on
cards computed from a [TYPICAL] 1" x 7/8" rod string over 1,150 m, a
crank-pitman surface unit and a single viscous-drag law (see the twin.dyno
module docstring and DYNO_CARD_MODEL.md section 6, "Known limits") -- a real
Baghewala string, unit geometry and valve wear will differ. Treat every
prediction as a first read to confirm with a pump specialist, not a
diagnosis. The first real measured card Oil India shares should be used to
re-fit this classifier (same idea as twin/calibrate.py's field recalibration
of the reservoir model) -- retrain with `python -m ml.dyno_classifier
--train`.

Features (`card_features()`, `FEATURE_NAMES`, 143 total) -- all computed on
the card AFTER converting to canonical units (m, kN) and normalising its
bounding box to [0, 1] x [0, 1], so they do not depend on the absolute stroke
length or load scale of a particular well/rod string, only on card SHAPE:
  * up_0..up_63, dn_0..dn_63 (128) -- normalised load vs. normalised position,
    resampled to 64 points on each of the up-stroke and down-stroke branches
    (branch split follows twin.dyno._branches's own convention: split at the
    position argmax/argmin, sort each half by position).
  * area_frac -- shoelace loop area / (position range x load range): how much
    of its own bounding box the loop fills (a thin rod-float egg vs. a fat
    parallelogram).
  * aspect_ratio_kN_per_m -- load range / position range, in the canonical
    units (not scale-free across wells, but consistent once units are fixed).
  * min_over_max, mean_over_max, min_over_mean -- load ratios (scale-free by
    construction: a ratio of two loads in the same unit).
  * downstroke_slope_mid -- linear-fit slope of the normalised downstroke
    over the middle 25-75% of the stroke (inertia peaks at the stroke ends,
    drag at mid-stroke -- DYNO_CARD_MODEL.md section 3), fully dimensionless.
  * zero_load_frac -- fraction of the (closed, normalised) loop's points at or
    below 5% of the load range: the rod-float / carrier-separation tell.
  * fourier_mag_1..8 -- magnitudes of the first 8 non-DC Fourier coefficients
    of the closed contour z(t) = position_norm(t) + i*load_norm(t), resampled
    to a uniform ARC-LENGTH parametrisation (robust to irregular sampling
    density) -- captures overall loop shape independent of the branch split
    or where around the loop the recording happened to start.

Usage:
    python -m ml.dyno_classifier --train                 # regenerate + retrain
    python -m ml.dyno_classifier --demo                  # classify the 8 baked cards
"""
