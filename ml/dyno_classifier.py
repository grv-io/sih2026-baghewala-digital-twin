# --------------------------------------------------------------------------
# Unit handling -- accept position_m/position_in, load_kN/load_klbf, and
# auto-detect by magnitude when the caller doesn't say.
# --------------------------------------------------------------------------
M_PER_IN = 0.0254
KN_PER_KLBF = 4.4482216152605
MIN_POINTS = 6
# Typical Baghewala-scale cards run 0.5-6 m of stroke, 20-280 in; typical
# loads run 0-150 kN (DYNO_CARD_MODEL.md section 5), 0-33 klbf. A position
# range above this many "metres" is almost certainly inches; a load whose
# largest magnitude is below this many "kN" is almost certainly klbf.
POS_RANGE_IN_GUESS_M = 12.0
LOAD_KLBF_GUESS_MAX = 40.0

_POSITION_COL_HINTS = {"position_m": "m", "pos_m": "m", "x_m": "m",
                        "position_in": "in", "pos_in": "in", "x_in": "in",
                        "position": None, "pos": None, "x": None}
_LOAD_COL_HINTS = {"load_kn": "kN", "prl_kn": "kN", "y_kn": "kN",
                    "load_klbf": "klbf", "prl_klbf": "klbf", "y_klbf": "klbf",
                    "load": None, "prl": None, "y": None}


def _detect_position_unit(position_raw: np.ndarray) -> str:
    return "in" if float(np.ptp(position_raw)) > POS_RANGE_IN_GUESS_M else "m"


def _detect_load_unit(load_raw: np.ndarray) -> str:
    return "klbf" if float(np.max(np.abs(load_raw))) < LOAD_KLBF_GUESS_MAX else "kN"


def _resolve_units(units: Any, position_raw: np.ndarray, load_raw: np.ndarray) -> tuple[str, str, bool]:
    """Returns (position_unit, load_unit, guessed) -- guessed is True if
    EITHER unit had to be inferred by magnitude rather than stated."""
    pos_unit = load_unit = None
    if isinstance(units, str):
        parts = [p.strip().lower() for p in units.split(",")]
        if len(parts) == 2:
            pos_unit, load_unit = parts
    elif isinstance(units, dict):
        pos_unit = (units.get("position") or units.get("position_unit") or None)
        load_unit = (units.get("load") or units.get("load_unit") or None)
        pos_unit = pos_unit.lower() if pos_unit else None
        load_unit = load_unit.lower() if load_unit else None
    guessed_pos = pos_unit not in ("m", "in")
    guessed_load = load_unit not in ("kn", "klbf")
    if guessed_pos:
        pos_unit = _detect_position_unit(position_raw)
    if guessed_load:
        load_unit = _detect_load_unit(load_raw)
    return pos_unit, ("klbf" if load_unit == "klbf" else "kN"), (guessed_pos or guessed_load)


def _to_canonical(position_raw: np.ndarray, load_raw: np.ndarray, units: Any = None):
    pos_unit, load_unit, guessed = _resolve_units(units, position_raw, load_raw)
    pos_m = position_raw * M_PER_IN if pos_unit == "in" else position_raw
    load_kN = load_raw * KN_PER_KLBF if load_unit == "klbf" else load_raw
    return pos_m, load_kN, {"position": pos_unit, "load": load_unit, "guessed": guessed}


def _validate_raw(position, load) -> tuple[np.ndarray, np.ndarray]:
    position = np.asarray(position, dtype=float).reshape(-1)
    load = np.asarray(load, dtype=float).reshape(-1)
    if len(position) != len(load):
        raise ValueError(f"position and load must be the same length (got {len(position)} vs {len(load)})")
    if len(position) < MIN_POINTS:
        raise ValueError(f"need at least {MIN_POINTS} points to read a dynamometer card (got {len(position)})")
    if not np.all(np.isfinite(position)) or not np.all(np.isfinite(load)):
        raise ValueError("position/load contain NaN or infinite values")
    if float(np.ptp(position)) <= 0:
        raise ValueError("position has zero range -- not a valid stroke")
    if float(np.ptp(load)) <= 0:
        raise ValueError("load has zero range -- not a valid card (no load variation)")
    return position, load


def parse_card_table(text: str) -> tuple[np.ndarray, np.ndarray, dict]:
    """Parse a CSV (with header) or a plain pasted two-column table (no
    header, comma/tab/whitespace separated) into (position, load, units).
    `units` has explicit "m"/"in"/"kN"/"klbf" values when the header names
    them, else None (caller auto-detects by magnitude in `_to_canonical`)."""
    raw = str(text).strip()
    if not raw:
        raise ValueError("empty input -- no rows found")
    lines = [ln for ln in raw.replace("\r", "").split("\n") if ln.strip()]
    if not lines:
        raise ValueError("empty input -- no rows found")

    def _split(line: str) -> list[str]:
        if "," in line:
            return [c.strip() for c in line.split(",")]
        if "\t" in line:
            return [c.strip() for c in line.split("\t")]
        return line.split()

    def _is_number(tok: str) -> bool:
        try:
            float(tok)
            return True
        except ValueError:
            return False

    first = _split(lines[0])
    has_header = len(first) >= 2 and not all(_is_number(t) for t in first)
    pos_unit = load_unit = None
    if has_header:
        header = [h.strip().lower().replace(" ", "_") for h in first]
        pos_idx = load_idx = None
        for i, h in enumerate(header):
            if pos_idx is None and h in _POSITION_COL_HINTS:
                pos_idx, pos_unit = i, _POSITION_COL_HINTS[h]
            if load_idx is None and h in _LOAD_COL_HINTS:
                load_idx, load_unit = i, _LOAD_COL_HINTS[h]
        if pos_idx is None:
            pos_idx = 0
        if load_idx is None:
            load_idx = 1 if len(header) > 1 else 0
        data_lines = lines[1:]
    else:
        pos_idx, load_idx = 0, 1
        data_lines = lines

    position, load = [], []
    for ln in data_lines:
        cells = _split(ln)
        if len(cells) <= max(pos_idx, load_idx):
            continue
        try:
            p, l = float(cells[pos_idx]), float(cells[load_idx])
        except ValueError:
            continue
        position.append(p)
        load.append(l)
    if len(position) < MIN_POINTS:
        raise ValueError(f"parsed only {len(position)} numeric row(s) -- need at least {MIN_POINTS}")
    return np.asarray(position), np.asarray(load), {"position": pos_unit, "load": load_unit}


# --------------------------------------------------------------------------
# Shape features
# --------------------------------------------------------------------------
N_BRANCH_POINTS = 64
N_CONTOUR_POINTS = 128
N_FOURIER = 8

FEATURE_NAMES = (
    [f"up_{i}" for i in range(N_BRANCH_POINTS)]
    + [f"dn_{i}" for i in range(N_BRANCH_POINTS)]
    + ["area_frac", "aspect_ratio_kN_per_m", "min_over_max", "mean_over_max", "min_over_mean",
       "downstroke_slope_mid", "zero_load_frac"]
    + [f"fourier_mag_{k}" for k in range(1, N_FOURIER + 1)]
)


def _close_loop(x: np.ndarray, f: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    if math.hypot(float(x[-1] - x[0]), float(f[-1] - f[0])) > 1e-9:
        x = np.append(x, x[0])
        f = np.append(f, f[0])
    return x, f


def _branches(x: np.ndarray, f: np.ndarray):
    """Split a closed, time-ordered card loop into (up-stroke, down-stroke),
    each sorted ascending by position -- mirrors twin.dyno._branches's own
    convention (duplicated here so ml/ has no import-time dependency on
    twin/dyno.py's private helpers)."""
    n = len(x)
    i_top, i_bot = int(np.argmax(x)), int(np.argmin(x))
    up = (np.arange(i_bot, i_bot + ((i_top - i_bot) % n) + 1)) % n
    dn = (np.arange(i_top, i_top + ((i_bot - i_top) % n) + 1)) % n
    out = []
    for idx in (up, dn):
        xs, fs = x[idx], f[idx]
        o = np.argsort(xs, kind="stable")
        out.append((xs[o], fs[o]))
    return out


def _resample_branch(xs: np.ndarray, fs: np.ndarray, n: int) -> np.ndarray:
    grid = np.linspace(0.0, 1.0, n)
    return np.interp(grid, xs, fs)


def _normalize(x: np.ndarray, f: np.ndarray):
    x_min, x_max = float(x.min()), float(x.max())
    f_min, f_max = float(f.min()), float(f.max())
    x_range = max(x_max - x_min, 1e-9)
    f_range = max(f_max - f_min, 1e-9)
    return (x - x_min) / x_range, (f - f_min) / f_range, x_range, f_range


def card_features(position_m, load_kN) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Feature vector (len(FEATURE_NAMES),) for one closed card, plus the
    normalised (x_n, f_n) arrays (reused by the fillage rule)."""
    x, f = _close_loop(np.asarray(position_m, dtype=float), np.asarray(load_kN, dtype=float))
    x_n, f_n, x_range, f_range = _normalize(x, f)

    (xu, fu), (xd, fd) = _branches(x_n, f_n)
    up = _resample_branch(xu, fu, N_BRANCH_POINTS)
    dn = _resample_branch(xd, fd, N_BRANCH_POINTS)

    area = 0.5 * abs(np.sum(x[:-1] * f[1:] - x[1:] * f[:-1]))
    area_frac = area / (x_range * f_range)
    aspect_ratio = f_range / x_range

    f_max, f_min, f_mean = float(f.max()), float(f.min()), float(f.mean())
    min_over_max = f_min / f_max if f_max != 0 else 0.0
    mean_over_max = f_mean / f_max if f_max != 0 else 0.0
    min_over_mean = f_min / f_mean if abs(f_mean) > 1e-9 else 0.0

    grid = np.linspace(0.0, 1.0, N_BRANCH_POINTS)
    mid = (grid >= 0.25) & (grid <= 0.75)
    downstroke_slope = float(np.polyfit(grid[mid], dn[mid], 1)[0]) if mid.sum() >= 2 else 0.0

    zero_load_frac = float(np.mean(f_n <= 0.05))

    d = np.hypot(np.diff(x_n), np.diff(f_n))
    s = np.concatenate([[0.0], np.cumsum(d)])
    total = s[-1] if s[-1] > 0 else 1.0
    t_grid = np.linspace(0.0, 1.0, N_CONTOUR_POINTS, endpoint=False)
    x_c = np.interp(t_grid, s / total, x_n)
    f_c = np.interp(t_grid, s / total, f_n)
    Z = np.fft.fft(x_c + 1j * f_c)
    fourier_mags = (np.abs(Z[1:N_FOURIER + 1]) / N_CONTOUR_POINTS).tolist()

    feats = np.concatenate([
        up, dn,
        np.array([area_frac, aspect_ratio, min_over_max, mean_over_max, min_over_mean,
                   downstroke_slope, zero_load_frac]),
        np.array(fourier_mags),
    ])
    return feats, x_n, f_n


def _fillage_rule(x_n: np.ndarray, f_n: np.ndarray) -> float:
    """Rule-based fillage estimate from the downstroke shape alone (no
    physics reference load available for a measured card): travel, from the
    top of the stroke down, before the normalised load first crosses below
    its own mid-range (0.5) -- mirrors twin.dyno.classify_card's card_fill
    definition, using a relative threshold instead of Fo/2."""
    (_, _), (xd, fd) = _branches(x_n, f_n)
    xr, fr = xd[::-1], fd[::-1]  # top -> bottom
    below = np.nonzero(fr < 0.5)[0]
    travel = float(xr[0] - xr[below[0]]) if len(below) else 1.0
    return float(np.clip(1.0 - travel, 0.0, 1.0))


def _quality_flags(position_raw: np.ndarray, load_raw: np.ndarray, unit_guessed: bool) -> dict:
    n = len(position_raw)
    diag = math.hypot(float(np.ptp(position_raw)), float(np.ptp(load_raw))) or 1.0
    d_close = math.hypot(float(position_raw[-1] - position_raw[0]), float(load_raw[-1] - load_raw[0]))
    return {
        "too_few_points": bool(n < 20),
        "not_closed_loop": bool(d_close > 0.15 * diag),
        "unit_guess": bool(unit_guessed),
    }


