_MODEL_CACHE: dict | None = None


def _load_model() -> dict:
    global _MODEL_CACHE
    if _MODEL_CACHE is None:
        if not MODEL_PATH.exists():
            raise FileNotFoundError(f"{MODEL_PATH} not found -- run `python -m ml.dyno_classifier --train` first.")
        _MODEL_CACHE = joblib.load(MODEL_PATH)
    return _MODEL_CACHE


def classify_card(position, load, units: Any = None) -> dict:
    """Classify a MEASURED surface dynamometer card.

    Args:
        position: sequence of polished-rod positions (any consistent unit).
        load: sequence of polished-rod loads (any consistent unit).
        units: None (auto-detect both by magnitude), a "position,load" string
            (e.g. "in,klbf"), or a {"position":.., "load":..} dict; either
            axis left None/unrecognised falls back to magnitude detection.

    Returns dict: card_type, probabilities (per class), fillage_est, peak_kN,
    min_kN, sentence_en, sentence_hi, quality_flags, model_caveat.

    Raises ValueError on malformed input (mismatched lengths, too few points,
    non-finite values, zero-range axis).
    """
    position_raw, load_raw = _validate_raw(position, load)
    pos_m, load_kN, unit_info = _to_canonical(position_raw, load_raw, units)
    flags = _quality_flags(pos_m, load_kN, unit_info["guessed"])
    flags["position_unit_used"] = unit_info["position"]
    flags["load_unit_used"] = unit_info["load"]

    feats, x_n, f_n = card_features(pos_m, load_kN)
    bundle = _load_model()
    clf, classes = bundle["model"], bundle["classes"]
    proba = clf.predict_proba(feats.reshape(1, -1))[0]
    card_type = classes[int(np.argmax(proba))]
    probabilities = {c: float(p) for c, p in zip(classes, proba)}

    fillage_est = _fillage_rule(x_n, f_n)
    kwargs = {"fillage": 100.0 * fillage_est}
    return {
        "card_type": card_type,
        "probabilities": probabilities,
        "fillage_est": fillage_est,
        "peak_kN": float(load_kN.max()),
        "min_kN": float(load_kN.min()),
        "sentence_en": SENTENCES["en"][card_type].format(**kwargs),
        "sentence_hi": SENTENCES["hi"][card_type].format(**kwargs),
        "quality_flags": flags,
        "model_caveat": MODEL_CAVEAT,
    }


def classify_baked_demo(scenario: str = "baseline") -> list[dict]:
    """Classify the (baseline scenario's) 4 baked cards in ml/models/
    dyno_cards.json against their own physics-derived card_type -- used by
    GET /api/dyno/classify/demo. `baseline` is picked deterministically (it
    is the console's default scenario); the other 4 (recommendation) are
    exercised individually in tests/test_dyno_classifier.py."""
    with open(BAKED_CARDS_PATH) as f:
        data = json.load(f)
    out = []
    for c in data["scenarios"][scenario]["cards"]:
        pred = classify_card(c["surface"]["position_m"], c["surface"]["load_kN"], units={"position": "m", "load": "kN"})
        out.append({
            "key": c["key"], "true_card_type": c["card_type"], "true_card_label": c["card_label"],
            "predicted_card_type": pred["card_type"], "probabilities": pred["probabilities"],
            "fillage_est": pred["fillage_est"], "true_fillage": c["pump_fillage"],
        })
    return out


