def _strata(rng: np.random.Generator, n: int) -> list[dict]:
    """Stratified sampling plan across (spm, mu_cP, fillage, water_cut, gas)
    so every card_type is well represented -- rod_float and gas_interference
    live in corners of the box a plain uniform draw under-covers."""
    fracs = {"general": 0.30, "low_mu": 0.20, "gas": 0.15, "viscous": 0.15, "rod_float": 0.20}
    counts = {k: int(round(n * f)) for k, f in fracs.items()}
    counts["general"] += n - sum(counts.values())  # absorb rounding remainder

    def block(n_i, spm_lo, spm_hi, mu_lo, mu_hi, fill_lo, fill_hi, gas_p):
        return {
            "spm": rng.uniform(spm_lo, spm_hi, n_i),
            "mu": np.exp(rng.uniform(math.log(mu_lo), math.log(mu_hi), n_i)),
            "fillage": rng.uniform(fill_lo, fill_hi, n_i),
            "water_cut": rng.uniform(0.6, 0.95, n_i),
            "gas": rng.random(n_i) < gas_p,
        }

    blocks = [
        block(counts["general"], 2.0, 12.0, 5.0, 15000.0, 0.4, 1.0, 0.25),
        block(counts["low_mu"], 2.0, 8.0, 5.0, 300.0, 0.4, 1.0, 0.0),
        block(counts["gas"], 2.0, 10.0, 5.0, 2000.0, 0.4, 0.9, 1.0),
        block(counts["viscous"], 3.0, 9.0, 500.0, 6000.0, 0.8, 1.0, 0.0),
        block(counts["rod_float"], 7.0, 12.0, 3000.0, 15000.0, 0.6, 1.0, 0.0),
    ]
    return blocks


def generate_dataset(params: dict, n_samples: int = 3200, seed: int = SEED):
    """Sweeps twin.dyno.compute_cards() to build a labelled synthetic
    training set (>= n_samples rows, stratified across spm 2-12, mu 5-15,000
    cP log-spaced, fillage 0.4-1.0, water_cut 0.6-0.95, the gas-interference
    option, and stroke +/-10% / depth +/-15% geometry perturbations), then
    corrupts each card with 1-3% load noise, 0.5% position noise and an
    irregular resampling to ~100 points -- imitating a real card reader
    rather than the clean 200-point simulator grid. Labels are compute_
    cards()'s own rule-based card_type (DYNO_CARD_MODEL.md section 3),
    computed from BOTH the surface and pump card; only the SURFACE card
    (what a measured dynamometer records) is fed to feature extraction.

    Returns (X, y, meta) -- X: (n, len(FEATURE_NAMES)) float array, y: (n,)
    array of card_type strings, meta: dict of generation counts."""
    from twin import dyno as twin_dyno

    rng = np.random.default_rng(seed)
    blocks = _strata(rng, n_samples)

    rows, labels = [], []
    n_attempted = 0
    n_failed = 0
    for blk in blocks:
        n_i = len(blk["spm"])
        stroke_mult = rng.uniform(0.90, 1.10, n_i)
        depth_mult = rng.uniform(0.85, 1.15, n_i)
        load_noise_frac = rng.uniform(0.01, 0.03, n_i)
        for i in range(n_i):
            n_attempted += 1
            try:
                card = twin_dyno.compute_cards(
                    spm=float(blk["spm"][i]),
                    stroke_m=_BASE_STROKE_M * float(stroke_mult[i]),
                    mu_cP=float(blk["mu"][i]),
                    fillage=float(blk["fillage"][i]),
                    water_cut=float(blk["water_cut"][i]),
                    params=params,
                    depth_m=_BASE_DEPTH_M * float(depth_mult[i]),
                    gas_interference=bool(blk["gas"][i]),
                    n_points=240,
                )
            except Exception:
                n_failed += 1
                continue

            x = np.asarray(card["position_m"], dtype=float)
            f = np.asarray(card["load_surface_kN"], dtype=float)
            if not (np.all(np.isfinite(x)) and np.all(np.isfinite(f))):
                n_failed += 1
                continue

            # measurement noise
            x_noisy = x + rng.normal(0.0, 0.005 * max(np.ptp(x), 1e-6), size=x.shape)
            f_noisy = f * (1.0 + rng.normal(0.0, float(load_noise_frac[i]), size=f.shape))

            # irregular resampling to ~100 points (jittered index grid, not a
            # clean uniform re-sample of the 240-point simulator grid)
            n_target = 100
            base_idx = np.linspace(0, len(x_noisy) - 1, n_target)
            jitter = rng.uniform(-0.5 * len(x_noisy) / n_target, 0.5 * len(x_noisy) / n_target, n_target)
            sel = np.clip(np.round(base_idx + jitter), 0, len(x_noisy) - 1).astype(int)
            sel = np.unique(sel)

            try:
                feats, _, _ = card_features(x_noisy[sel], f_noisy[sel])
            except Exception:
                n_failed += 1
                continue

            rows.append(feats)
            labels.append(card["card_type"])

    X = np.vstack(rows)
    y = np.asarray(labels)
    meta = {"n_attempted": n_attempted, "n_failed": n_failed, "n_rows": len(y),
            "class_counts": {c: int((y == c).sum()) for c in sorted(set(y.tolist()))}}
    return X, y, meta


# --------------------------------------------------------------------------
# Training
# --------------------------------------------------------------------------
def train(params: dict, n_samples: int = 3200, seed: int = SEED,
          out_model: Path = MODEL_PATH, out_metrics: Path = METRICS_PATH) -> dict:
    X, y, gen_meta = generate_dataset(params, n_samples=n_samples, seed=seed)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=seed, stratify=y
    )
    clf = RandomForestClassifier(
        n_estimators=400, max_depth=None, min_samples_leaf=2,
        class_weight="balanced_subsample", random_state=seed, n_jobs=-1,
    )
    clf.fit(X_train, y_train)
    classes = clf.classes_.tolist()

    y_pred = clf.predict(X_test)
    acc = float(accuracy_score(y_test, y_pred))
    report = classification_report(y_test, y_pred, labels=classes, output_dict=True, zero_division=0)
    per_class_f1 = {c: float(report[c]["f1-score"]) for c in classes}
    cm = confusion_matrix(y_test, y_pred, labels=classes).tolist()

    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    bundle = {
        "model": clf, "classes": classes, "feature_names": FEATURE_NAMES,
        "seed": seed, "trained_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    joblib.dump(bundle, out_model)
    if Path(out_model) == MODEL_PATH:
        # Refresh classify_card()'s in-memory cache so a retrain takes effect
        # immediately, without waiting for the next cold `_load_model()` --
        # only when writing to the canonical path (a retrain to a scratch
        # path, e.g. a determinism test, must not disturb the live model).
        global _MODEL_CACHE
        _MODEL_CACHE = bundle

    metrics = {
        "trained_at_utc": bundle["trained_at_utc"],
        "seed": seed,
        "n_samples_requested": n_samples,
        "generation": gen_meta,
        "n_train": int(len(y_train)),
        "n_test": int(len(y_test)),
        "classes": classes,
        "accuracy": acc,
        "per_class_f1": per_class_f1,
        "confusion_matrix": cm,
        "confusion_matrix_labels": classes,
        "n_features": len(FEATURE_NAMES),
        "model": "RandomForestClassifier(n_estimators=400, class_weight='balanced_subsample')",
        "feature_note": "128 resampled up/down-stroke shape points + 7 scale-free ratios/slope + 8 Fourier "
                         "magnitudes -- see ml/dyno_classifier.py module docstring and FEATURE_NAMES.",
        "domain_shift_caveat": MODEL_CAVEAT,
    }
    with open(out_metrics, "w") as f:
        json.dump(metrics, f, indent=2)

    print(f"Generated {gen_meta['n_rows']} cards ({gen_meta['n_failed']} skipped of {gen_meta['n_attempted']} attempted)")
    print(f"Class counts: {gen_meta['class_counts']}")
    print(f"Train/test: {len(y_train)}/{len(y_test)} (seed={seed})")
    print(f"Accuracy: {acc:.4f}")
    for c in classes:
        print(f"  F1[{c}] = {per_class_f1[c]:.4f}")
    print(f"Saved model -> {out_model}\nSaved metrics -> {out_metrics}")
    return metrics


def _main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--train", action="store_true", help="regenerate the synthetic dataset and retrain")
    ap.add_argument("--demo", action="store_true", help="classify the 8 baked cards vs. their true label")
    ap.add_argument("--n-samples", type=int, default=3200)
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument("--params", default=str(DEFAULT_PARAMS_PATH))
    args = ap.parse_args(argv)

    with open(args.params) as f:
        params = json.load(f)

    if args.train:
        train(params, n_samples=args.n_samples, seed=args.seed)
    if args.demo or not args.train:
        for scenario in ("baseline", "recommendation"):
            for row in classify_baked_demo(scenario):
                match = "OK" if row["predicted_card_type"] == row["true_card_type"] else "MISS"
                print(f"[{match}] {scenario}:{row['key']:13s} true={row['true_card_type']:18s} "
                      f"pred={row['predicted_card_type']:18s} p={row['probabilities'][row['predicted_card_type']]:.2f}")


if __name__ == "__main__":
    _main()
